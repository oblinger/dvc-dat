"""`dvc_dat.just`: declared commands and the generated `.dat/targets.just`.

    from dvc_dat.just import command

    @command(args="game=…", help="train the model on one game")
    @ledger_fn
    def train(rev, *, game: str, path: Path) -> StageDat: ...

`just run TARGET` runs any target; a *command* also runs as `just <name>`.
A function is a command when `@command` marks it; a spec (a mounted mapping)
when its `command:` key is `true` or `{args: …, help: …}`.  Each mounted name
that is a command, or each command defined in a mounted module, gets one
recipe in `.dat/targets.just` beside `.datconfig.yaml`: `just <name> k=v …` is
`just run <target> k=v …`, `<name>` the last part of the target (a spec
mounted from a folder, `specs/table12`, is `just table12`, running
`specs.table12`).  A project's justfile opts in with
`import? '.dat/targets.just'`; the `run` recipe rewrites the file when it is
older than the config, the justfile or a mounted source, and says on stderr
what it wrote and what it skipped.  A name the justfile already has (a hand
recipe, `run`, `mounts`) is skipped: the hand recipe wins.

`args` and `help` are explicit and short, so `just --list` stays one screen:
`args` at most ARGS_MAX characters, `help` at most HELP_MAX per line with one
newline allowed (a second line); over budget is `ValueError` at import.
"""

import os
import re
import subprocess
import sys
from pathlib import Path
from types import ModuleType
from typing import Any, Callable, Dict, List, Optional, Tuple

ARGS_MAX = 24
HELP_MAX = 56
TARGETS = Path(".dat") / "targets.just"
ENV_JUSTFILE = "DAT_JUSTFILE"     # set by the `run` recipe: the justfile it runs under
_ATTR = "__dat_command__"
_RECIPE_NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_-]*$")
_GENERATED = re.compile(r"^([A-Za-z_][A-Za-z0-9_-]*) \*args:$", re.M)
_HEADER = "# Generated by dvc_dat.just from the mounted commands; rewritten, never edited.\n"


def _check(args: Any, help: Any, where: str) -> Tuple[str, str]:
    if not isinstance(args, str) or not isinstance(help, str):
        raise TypeError(f"{where}: args and help are strings, got {args!r}, {help!r}")
    if "\n" in args or len(args) > ARGS_MAX:
        raise ValueError(f"{where}: args is one line of at most {ARGS_MAX} characters, got {args!r}")
    lines = help.split("\n")
    if not help or len(lines) > 2 or any(not line or len(line) > HELP_MAX for line in lines):
        raise ValueError(f"{where}: help is one or two non-empty lines of at most {HELP_MAX} "
                         f"characters, got {help!r}")
    return args, help


def command(*, args: str, help: str) -> Callable[[Callable], Callable]:
    """Mark a function a command: `just <name>` runs it.  Returns the function unchanged."""
    _check(args, help, "@command")

    def mark(fn: Callable) -> Callable:
        if not callable(fn):
            raise TypeError(f"@command goes on a function, not {fn!r}")
        setattr(fn, _ATTR, {"args": args, "help": help})
        return fn
    return mark


def declared(obj: Any, where: str = "spec") -> Optional[Dict[str, str]]:
    """The `{args, help}` a command declares, else None (not a command)."""
    if callable(obj) and not isinstance(obj, type):
        return getattr(obj, _ATTR, None)
    if isinstance(obj, dict) and obj.get("command"):
        decl = obj["command"]
        if decl is True:
            return {"args": "", "help": ""}
        if not isinstance(decl, dict) or set(decl) - {"args", "help"}:
            raise ValueError(f"{where}: command is true or {{args: …, help: …}}, got {decl!r}")
        args, help = _check(decl.get("args", ""), decl.get("help", ""), where)
        return {"args": args, "help": help}
    return None


def commands(ns: Any) -> Tuple[Dict[str, Tuple[str, Dict[str, str]]], List[str]]:
    """`{recipe name: (target, decl)}` for every command the namespace mounts, and what was skipped."""
    found: Dict[str, Tuple[str, Dict[str, str]]] = {}
    skipped: List[str] = []

    def add(name: str, target: str, decl: Dict[str, str]) -> None:
        if not _RECIPE_NAME.match(name):
            skipped.append(f"{target} (not a recipe name)")
        elif name in found:
            skipped.append(f"{target} ({name} is also {found[name][0]})")
        else:
            found[name] = (target, decl)

    if hasattr(ns, "_commands"):                    # a ledger project: read off the mounted files
        for target, decl, _file in ns._commands():
            add(target.rpartition(".")[2], target, decl)
        return found, skipped
    values = set(ns._registered_values or ())
    for key in sorted(set(ns._mounted_names()) | values):
        try:
            base = None if key in values else ns._get_base(key, default=None)
            if isinstance(base, ModuleType):
                for attr, obj in sorted(vars(base).items()):
                    if getattr(obj, "__module__", None) == base.__name__ and (decl := declared(obj)):
                        add(attr, f"{key}.{attr}", decl)
                continue
            obj = ns.load(key, default=None)
            if (decl := declared(obj, key)):
                dotted = key.replace("/", ".")         # a folder mount's `specs/table12` is `specs.table12`
                add(dotted.rpartition(".")[2], dotted, decl)
        except Exception as e:   # a name that does not load is not a command; say so
            skipped.append(f"{key} (does not load: {e})")
    return found, skipped


def _quote(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def render(found: Dict[str, Tuple[str, Dict[str, str]]]) -> str:
    """The text of `.dat/targets.just`."""
    out = [_HEADER]
    for name, (target, decl) in sorted(found.items()):
        doc = "  ".join(part for part in (decl["args"], decl["help"]) if part)
        out.append(f"\n[doc({_quote(doc)})]" if doc else "\n")
        out.append("\n[group('run')]\n[no-cd]\n[positional-arguments]\n"
                   f"{name} *args:\n"
                   f"    @\"{{{{just_executable()}}}}\" -f \"{{{{justfile()}}}}\" run '{target}' \"$@\"\n")
    return "".join(out)


def _sources(ns: Any) -> List[Path]:
    """The files a mounted name loads from, as far as they are known."""
    out = [f for _t, _d, f in ns._commands()] if hasattr(ns, "_commands") else []
    for key, location in list(ns._base_locations.items()):
        if isinstance(location, str) and os.path.exists(location):
            out.append(Path(location))
        obj = ns._base_objects.get(key) if hasattr(ns, "_base_objects") else None
        if isinstance(obj, ModuleType) and getattr(obj, "__file__", None):
            out.append(Path(obj.__file__))
    main = sys.modules.get("__main__")
    if main is not None and getattr(main, "__file__", None):
        out.append(Path(main.__file__))
    return out


def _mtime(path: Path) -> float:
    try:
        return path.stat().st_mtime
    except OSError:
        return 0.0


def refresh(ns: Any, config_dir: Path, justfile: Path, *, err: Any = None) -> bool:
    """Rewrite `<config_dir>/.dat/targets.just` when it is stale; True when written.

    Only a justfile that imports `.dat/targets.just` gets one.  Stale is missing,
    or older than the config, the justfile, or a mounted source.  The justfile's
    own recipes (those not generated last time) are skipped, by name.
    """
    err = err or sys.stderr
    if not justfile.is_file() or str(TARGETS) not in justfile.read_text():
        return False
    target = config_dir / TARGETS
    if target.exists():
        newest = max([_mtime(config_dir / ".datconfig.yaml"), _mtime(justfile)]
                     + [_mtime(p) for p in _sources(ns)])
        if _mtime(target) >= newest:
            return False
    found, skipped = commands(ns)
    generated = set(_GENERATED.findall(target.read_text())) if target.exists() else set()
    summary = subprocess.run([os.environ.get("JUST", "just"), "-f", str(justfile), "--summary"],
                             capture_output=True, text=True)
    if summary.returncode != 0:
        raise RuntimeError(f"just --summary on {justfile}: {summary.stderr.strip()}")
    hand = set(summary.stdout.split()) - generated
    for name in sorted(set(found) & hand):
        skipped.append(f"{found.pop(name)[0]} ({name} is a recipe in the justfile)")
    target.parent.mkdir(parents=True, exist_ok=True)
    text = render(found)
    if not target.exists() or target.read_text() != text:
        target.write_text(text)
    else:
        os.utime(target)
    print(f"targets: {os.path.relpath(target)} ({len(found)} command(s))"
          + ("; skipped " + ", ".join(skipped) if skipped else ""), file=err)
    return True


__all__ = ["ARGS_MAX", "HELP_MAX", "command", "declared", "commands", "render", "refresh"]
